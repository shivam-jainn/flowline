#!/usr/bin/env bash
# sync-env.sh — materialize a .env file from a Pulumi stack. No copy-paste.
#
# Usage: sync-env.sh <stack> <output-file>
#   e.g. sync-env.sh dev-flowline ../../.env.development   (run from webapp/)
#        sync-env.sh prod ../../.env.production
#
# Sources (in order):
#   1. Vaultwarden (env-wise folders flowline-dev/flowline-prod) — primary
#   2. Stack outputs  (fallback when BW_SESSION is unset, e.g. CI)
#   3. Stack config   (one-time manual secrets via `pulumi config set --secret`)
#
# Requires: pulumi CLI + PULUMI_CONFIG_PASSPHRASE (or ~/.pulumi-passphrase).
set -euo pipefail

STACK="${1:?usage: sync-env.sh <stack> <output-file>}"
OUT="${2:?usage: sync-env.sh <stack> <output-file>}"

INFRA_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

if [[ -z "${PULUMI_CONFIG_PASSPHRASE:-}" && -f "$HOME/.pulumi-passphrase" ]]; then
  export PULUMI_CONFIG_PASSPHRASE
  PULUMI_CONFIG_PASSPHRASE="$(cat "$HOME/.pulumi-passphrase")"
fi
if [[ -z "${PULUMI_CONFIG_PASSPHRASE:-}" ]]; then
  echo "error: PULUMI_CONFIG_PASSPHRASE is not set and ~/.pulumi-passphrase not found" >&2
  exit 1
fi

# output-name -> ENV_VAR
STACK_OUTPUTS=(
  "databaseUrl:DATABASE_URL"
)
# config-key -> ENV_VAR (optional: skipped with a warning when unset)
SECRET_CONFIG=(
  "googleClientId:GOOGLE_CLIENT_ID"
  "googleClientSecret:GOOGLE_CLIENT_SECRET"
)
# Vaultwarden items are the primary source (env-wise folders):
#   folder `flowline-dev`  -> item `flowline-neon-dev`  (dev DATABASE_URL)
#   folder `flowline-prod` -> item `flowline-neon-prod` (prod DATABASE_URL).
# Requires: `bw config server <url>`, `bw login`, and BW_SESSION set (see `bw unlock`).
# If the server uses a mkcert (local-CA) cert, export:
#   NODE_EXTRA_CA_CERTS="$(mkcert -CAROOT)/rootCA.pem"
# (Node doesn't read the macOS keychain; `mkcert -install` covers browsers + desktop app.)
if [[ "$STACK" == "prod" ]]; then
  BW_ITEMS=(
    "flowline-neon-prod:DATABASE_URL"
  )
else
  BW_ITEMS=(
    "flowline-neon-dev:DATABASE_URL"
  )
fi

get_output() {
  pulumi --cwd "$INFRA_DIR" stack output "$1" --show-secrets --stack "$STACK" 2>/dev/null || true
}

get_config() {
  pulumi --cwd "$INFRA_DIR" config get "$1" --stack "$STACK" 2>/dev/null || true
}

get_bw() {
  command -v bw >/dev/null 2>&1 || return 0
  if [[ -z "${BW_SESSION:-}" ]]; then
    echo "warn: BW_SESSION not set — 'bw unlock' first to enable vault-sourced vars" >&2
    return 0
  fi
  bw get password "$1" --session "$BW_SESSION" 2>/dev/null || true
}

SEEN_VARS=""
emit() {
  case " $SEEN_VARS " in
    *" $1 "*) return 0 ;;
  esac
  SEEN_VARS="$SEEN_VARS $1"
  printf '%s=%s\n' "$1" "$2"
}

TMP="$(mktemp)"
{
  echo "# GENERATED by infra/scripts/sync-env.sh from stack '$STACK' on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# Do not edit. Do not commit. Re-run the script to refresh."
  for mapping in "${BW_ITEMS[@]}"; do
    [[ "$mapping" == \#* ]] && continue
    key="${mapping%%:*}"; var="${mapping##*:}"
    val="$(get_bw "$key")"
    if [[ -n "$val" ]]; then
      echo "info: $var from vault item '$key'" >&2
      emit "$var" "$val"
    fi
  done
  for mapping in "${STACK_OUTPUTS[@]}"; do
    key="${mapping%%:*}"; var="${mapping##*:}"
    case " $SEEN_VARS " in *" $var "*) continue ;; esac
    val="$(get_output "$key")"
    if [[ -z "$val" ]]; then
      echo "warn: stack output '$key' is empty (stack not deployed?) — skipped" >&2
      continue
    fi
    emit "$var" "$val"
  done
  for mapping in "${SECRET_CONFIG[@]}"; do
    key="${mapping%%:*}"; var="${mapping##*:}"
    case " $SEEN_VARS " in *" $var "*) continue ;; esac
    val="$(get_config "$key")"
    if [[ -z "$val" ]]; then
      echo "warn: config '$key' not set — run: pulumi config set --secret $key <value> --stack $STACK" >&2
      continue
    fi
    emit "$var" "$val"
  done
} > "$TMP"

chmod 600 "$TMP"
mv "$TMP" "$OUT"

# Anti-footgun: the generated file must be gitignored (plaintext secrets on disk
# are only acceptable if they can never be committed).
if git -C "$INFRA_DIR" check-ignore -q "$OUT" 2>/dev/null; then
  echo "ok: wrote $OUT ($(grep -c '=' "$OUT") vars, mode 600, gitignored)"
else
  echo "warn: $OUT is NOT gitignored — add it to .gitignore before it can hold secrets" >&2
  echo "ok: wrote $OUT ($(grep -c '=' "$OUT") vars, mode 600)"
fi
