//! Shell projection — string generation ONLY, no execution.
//!
//! Terminal commands become shell lines (redacted first, then single-quoted);
//! clicks/typing become comments since plain shell cannot replay GUI input.

use crate::ScriptStep;

/// Single-quote for POSIX shell. Applied AFTER redaction; placeholders
/// contain no single quotes so they survive intact.
fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// Render steps as a shell script. Secrets appear only as
/// `{{secret:<kind>}}` placeholders.
pub fn render(steps: &[ScriptStep]) -> String {
    let mut out = String::from("#!/bin/sh\n# Generated by step-it (replay sketch; review before running)\n");
    for step in steps {
        out.push_str(&format!("# Step: {}\n", step.description));
        match step.action.as_str() {
            "terminal" | "write_code" => {
                out.push_str(&step.redacted_text().lines().collect::<Vec<_>>().join("\n"));
                out.push('\n');
            }
            "typing" => {
                out.push_str(&format!(
                    "# typing (redacted): {}\n",
                    sh_quote(&step.redacted_text())
                ));
            }
            "click" | "right_click" | "double_click" | "key_press" => {
                out.push_str(&format!("# automation: {} (no shell equivalent)\n", step.action));
            }
            other => {
                out.push_str(&format!("# automation: {other} (unmapped action)\n"));
            }
        }
    }
    out
}
