//! Python projection — string generation ONLY, no execution.
//!
//! Clicks become commented automation actions, typing becomes redacted-safe
//! literals, terminal commands become shell lines inside a `subprocess` call.

use crate::ScriptStep;

/// Escape a string as a Python double-quoted literal (JSON escaping is a
/// valid subset for the characters we emit; placeholders contain no quotes).
fn py_string(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| "\"\"".to_string())
}

/// Render steps as a Python replay script. Secrets appear only as
/// `{{secret:<kind>}}` placeholders.
pub fn render(steps: &[ScriptStep]) -> String {
    let mut out = String::from("# Generated by step-it (replay sketch; review before running)\n");
    for step in steps {
        out.push_str(&format!("# Step: {}\n", step.description));
        match step.action.as_str() {
            "click" | "right_click" | "double_click" => {
                out.push_str(&format!(
                    "# automation: {} -- wire to your driver (e.g. pyautogui.click())\n",
                    step.action
                ));
            }
            "typing" => {
                out.push_str(&format!(
                    "type_text({})  # fill with your typing helper\n",
                    py_string(&step.redacted_text())
                ));
            }
            "terminal" | "write_code" => {
                out.push_str(&format!(
                    "subprocess.run({}, shell=True, check=True)\n",
                    py_string(&step.redacted_text())
                ));
            }
            "key_press" => {
                out.push_str(&format!(
                    "press_hotkey({})  # fill with your hotkey helper\n",
                    py_string(&step.redacted_text())
                ));
            }
            other => {
                out.push_str(&format!("# automation: {other} (unmapped action)\n"));
            }
        }
    }
    out
}
