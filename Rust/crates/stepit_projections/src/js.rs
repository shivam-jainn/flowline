//! JavaScript projection — string generation ONLY, no execution.

use crate::ScriptStep;

/// Escape a string as a JS double-quoted literal (JSON escaping suffices;
/// placeholders contain no quotes or backslashes).
fn js_string(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| "\"\"".to_string())
}

/// Render steps as a JS replay sketch. Secrets appear only as
/// `{{secret:<kind>}}` placeholders.
pub fn render(steps: &[ScriptStep]) -> String {
    let mut out = String::from("// Generated by step-it (replay sketch; review before running)\n");
    for step in steps {
        out.push_str(&format!("// Step: {}\n", step.description));
        match step.action.as_str() {
            "click" | "right_click" | "double_click" => {
                out.push_str(&format!(
                    "// automation: {} -- wire to your driver (e.g. robotjs.mouseClick())\n",
                    step.action
                ));
            }
            "typing" => {
                out.push_str(&format!(
                    "await typeText({}); // fill with your typing helper\n",
                    js_string(&step.redacted_text())
                ));
            }
            "terminal" | "write_code" => {
                out.push_str(&format!(
                    "await execCmd({}); // fill with child_process.exec\n",
                    js_string(&step.redacted_text())
                ));
            }
            "key_press" => {
                out.push_str(&format!(
                    "await pressHotkey({}); // fill with your hotkey helper\n",
                    js_string(&step.redacted_text())
                ));
            }
            other => {
                out.push_str(&format!("// automation: {other} (unmapped action)\n"));
            }
        }
    }
    out
}
