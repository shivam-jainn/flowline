                <button id="theme-selector-btn" class="action-btn theme-btn" title="Switch Theme (T)" aria-haspopup="true" aria-expanded="false">
                    <svg class="theme-icon" width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="5"></circle><line x1="12" y1="1" x2="12" y2="3"></line><line x1="12" y1="21" x2="12" y2="23"></line><line x1="4.22" y1="4.22" x2="5.64" y2="5.64"></line><line x1="18.36" y1="18.36" x2="19.78" y2="19.78"></line><line x1="1" y1="12" x2="3" y2="12"></line><line x1="21" y1="12" x2="23" y2="12"></line><line x1="4.22" y1="19.78" x2="5.64" y2="18.36"></line><line x1="18.36" y1="5.64" x2="19.78" y2="4.22"></line></svg>
                    <span id="theme-btn-label" class="btn-text">\(theme.displayName)</span>
                    <svg width="10" height="10" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5"><polyline points="6 9 12 15 18 9"></polyline></svg>
                </button>
                <div id="theme-dropdown-menu" class="theme-menu-popover hidden">
                    <button class="theme-option \(theme == .modernMinimal ? "active" : "")" data-theme-val="modern-minimal">
                        <span class="theme-color-dot minimal-dot"></span>
                        <span class="theme-opt-name">Modern Minimalist</span>
                    </button>
                    <button class="theme-option \(theme == .developerDark ? "active" : "")" data-theme-val="developer-dark">
