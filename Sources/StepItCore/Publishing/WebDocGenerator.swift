public final class WebDocGenerator: @unchecked Sendable {
    public static let shared = WebDocGenerator()
    
    public init() {}
    
    public func generateHTML(
        session: StepSession,
        settings: PublishingSettings = PublishingSettings(),
        assetBaseURL: String = ""
    ) -> String {
        let theme = session.theme
        let cssTheme = getThemeCSS(for: theme)
        let stepsHTML = generateStepsHTML(session: session, assetBaseURL: assetBaseURL)
        let sidebarNavHTML = generateSidebarNav(session: session)
        let headerMetadata = generateHeaderMetadata(session: session, settings: settings)
        
        let html = """
<!DOCTYPE html>
<html lang="en" data-theme="\(theme.rawValue)">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>\(session.title) — StepIt Guide</title>
    <meta name="description" content="Step-by-step workflow documentation generated by StepIt macOS.">
    <link rel="preconnect" href="https://fonts.googleapis.com">
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
    <link href="https://fonts.googleapis.com/css2?family=Plus+Jakarta+Sans:wght@400;500;600;700;800&family=JetBrains+Mono:wght@400;500;600&display=swap" rel="stylesheet">
    <style>
        \(cssTheme)
    </style>
</head>
<body>
    <!-- Top Progress Bar -->
    <div id="progress-bar-container">
        <div id="progress-bar"></div>
    </div>

    <!-- Top Navigation Header -->
    <header class="site-header">
        <div class="header-left">
            <div class="brand-badge">⚡️ StepIt</div>
            <span class="header-title">\(session.title)</span>
        </div>
        <div class="header-actions">
            <button id="toggle-checklist-btn" class="action-btn" title="Toggle Checklist Mode">
                <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="9 11 12 14 22 4"></polyline><path d="M21 12v7a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h11"></path></svg>
                <span>Checklist Mode</span>
            </button>
            <button id="copy-link-btn" class="action-btn" title="Share Guide">
                <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M10 13a5 5 0 0 0 7.54.54l3-3a5 5 0 0 0-7.07-7.07l-1.72 1.71"></path><path d="M14 11a5 5 0 0 0-7.54-.54l-3 3a5 5 0 0 0 7.07 7.07l1.71-1.71"></path></svg>
                <span>Share</span>
            </button>
            <button onclick="window.print()" class="action-btn" title="Print as PDF">
                <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="6 9 6 2 18 2 18 9"></polyline><path d="M6 18H4a2 2 0 0 1-2-2v-5a2 2 0 0 1 2-2h16a2 2 0 0 1 2 2v5a2 2 0 0 1-2 2h-2"></path><rect x="6" y="14" width="12" height="8"></rect></svg>
                <span>Print PDF</span>
            </button>
        </div>
    </header>

    <div class="layout-container">
        <!-- Sticky Sidebar Navigation -->
        <aside class="sidebar-nav">
            <div class="sidebar-header">
                <h3>Workflow Steps</h3>
                <span id="step-completion-badge" class="badge">0 / \(session.steps.count)</span>
            </div>
            <nav class="steps-menu">
                \(sidebarNavHTML)
            </nav>
            <div class="sidebar-footer">
                <small>Generated via <strong>StepIt macOS</strong></small>
            </div>
        </aside>

        <!-- Main Content Area -->
        <main class="main-content">
            <!-- Document Hero / Header -->
            <section class="doc-hero">
                <div class="hero-badge">Verified Workflow</div>
                <h1 class="hero-title">\(session.title)</h1>
                \(headerMetadata)
                \(session.summary != nil ? "<p class=\"doc-summary\">\(session.summary!)</p>" : "")
            </section>

            <!-- Steps Section -->
            <section class="steps-flow">
                \(stepsHTML)
            </section>

            <!-- Complete Footer -->
            <footer class="doc-footer">
                <div class="footer-card">
                    <h3>🎉 Workflow Finished</h3>
                    <p>You have reviewed all \(session.steps.count) steps in this guide.</p>
                    <button class="primary-btn" onclick="window.scrollTo({top: 0, behavior: 'smooth'})">Back to Top</button>
                </div>
            </footer>
        </main>
    </div>

    <!-- JavaScript for Interactivity -->
    <script>
        // Checklist progress and persistence
        const sessionId = "\(session.id)";
        const checkboxes = document.querySelectorAll('.step-check');
        const badge = document.getElementById('step-completion-badge');
        const progressBar = document.getElementById('progress-bar');

        function loadChecklist() {
            const saved = JSON.parse(localStorage.getItem('stepit_' + sessionId) || '{}');
            checkboxes.forEach(cb => {
                const stepIdx = cb.dataset.step;
                if (saved[stepIdx]) {
                    cb.checked = true;
                    document.getElementById('step-card-' + stepIdx)?.classList.add('step-completed');
                    document.getElementById('nav-item-' + stepIdx)?.classList.add('nav-done');
                }
            });
            updateProgress();
        }

        function updateProgress() {
            const total = checkboxes.length;
            const checked = document.querySelectorAll('.step-check:checked').length;
            if (badge) badge.textContent = `${checked} / ${total}`;
            if (progressBar && total > 0) {
                const pct = (checked / total) * 100;
                progressBar.style.width = pct + '%';
            }
        }

        checkboxes.forEach(cb => {
            cb.addEventListener('change', () => {
                const stepIdx = cb.dataset.step;
                const card = document.getElementById('step-card-' + stepIdx);
                const nav = document.getElementById('nav-item-' + stepIdx);
                
                if (cb.checked) {
                    card?.classList.add('step-completed');
                    nav?.classList.add('nav-done');
                } else {
                    card?.classList.remove('step-completed');
                    nav?.classList.remove('nav-done');
                }
                
                const saved = JSON.parse(localStorage.getItem('stepit_' + sessionId) || '{}');
                saved[stepIdx] = cb.checked;
                localStorage.setItem('stepit_' + sessionId, JSON.stringify(saved));
                updateProgress();
            });
        });

        // Media View Switcher (Screenshot vs GIF vs WebM)
        function switchMediaView(stepIndex, mode) {
            const card = document.getElementById('step-card-' + stepIndex);
            if (!card) return;
            const views = card.querySelectorAll('.media-view');
            views.forEach(v => v.classList.add('hidden'));
            
            const targetView = card.querySelector('.media-view-' + mode);
            if (targetView) targetView.classList.remove('hidden');
            
            const btns = card.querySelectorAll('.media-tab-btn');
            btns.forEach(b => b.classList.remove('active'));
            const activeBtn = card.querySelector(`[data-mode="${mode}"]`);
            if (activeBtn) activeBtn.classList.add('active');
        }

        // Copy Text Tooltip
        function copyText(text, btnElement) {
            navigator.clipboard.writeText(text).then(() => {
                const original = btnElement.innerHTML;
                btnElement.innerHTML = '✓ Copied';
                btnElement.classList.add('copied');
                setTimeout(() => {
                    btnElement.innerHTML = original;
                    btnElement.classList.remove('copied');
                }, 2000);
            });
        }

        // Share button
        document.getElementById('copy-link-btn')?.addEventListener('click', function() {
            copyText(window.location.href, this);
        });

        // ScrollSpy for Active Sidebar Nav
        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    const id = entry.target.id;
                    const stepIdx = id.replace('step-card-', '');
                    document.querySelectorAll('.nav-link').forEach(l => l.classList.remove('active'));
                    document.getElementById('nav-item-' + stepIdx)?.classList.add('active');
                }
            });
        }, { rootMargin: '-20% 0px -60% 0px' });

        document.querySelectorAll('.step-card').forEach(card => observer.observe(card));

        document.addEventListener('DOMContentLoaded', loadChecklist);
    </script>
</body>
</html>
"""
        return html
    }
    
    private func generateSidebarNav(session: StepSession) -> String {
        var html = ""
        for step in session.steps {
            html += """
            <a href="#step-card-\(step.index)" class="nav-link" id="nav-item-\(step.index)">
                <span class="nav-num">\(step.index)</span>
                <span class="nav-label">\(escapeHTML(step.actionDescription))</span>
            </a>
            """
        }
        return html
    }
    
    private func generateHeaderMetadata(session: StepSession, settings: PublishingSettings) -> String {
        return """
        <div class="metadata-grid">
            <div class="meta-item">
                <span class="meta-label">Author / Organization</span>
                <span class="meta-value">\(settings.authorName.isEmpty ? settings.companyName : settings.authorName)</span>
            </div>
            <div class="meta-item">
                <span class="meta-label">Recorded At</span>
                <span class="meta-value">\(session.startedAt.formatted(date: .abbreviated, time: .shortened))</span>
            </div>
            <div class="meta-item">
                <span class="meta-label">Total Steps</span>
                <span class="meta-value">\(session.steps.count) steps</span>
            </div>
            <div class="meta-item">
                <span class="meta-label">Capture Mode</span>
                <span class="meta-value">\(session.mediaMode.displayName)</span>
            </div>
        </div>
        """
    }
    
    private func generateStepsHTML(session: StepSession, assetBaseURL: String) -> String {
        var html = ""
        let prefix = assetBaseURL.isEmpty ? "" : (assetBaseURL.hasSuffix("/") ? assetBaseURL : "\(assetBaseURL)/")
        
        for step in session.steps {
            let hasScreenshot = step.assets.screenshot != nil
            let hasGif = step.assets.gif != nil
            let hasWebm = step.assets.webm != nil
            
            let defaultView = (hasGif && session.mediaMode != .staticOnly) ? "gif" : "screenshot"
            
            html += """
            <article class="step-card" id="step-card-\(step.index)">
                <div class="step-header">
                    <div class="step-left-header">
                        <label class="step-checkbox-container" title="Mark as completed">
                            <input type="checkbox" class="step-check" data-step="\(step.index)">
                            <span class="checkmark"></span>
                        </label>
                        <div class="step-badge">Step \(step.index)</div>
                        <h2 class="step-title">\(escapeHTML(step.actionDescription))</h2>
                    </div>
                    <div class="step-meta-chips">
                        \(step.appName.isEmpty ? "" : "<span class=\"chip app-chip\">\(escapeHTML(step.appName))</span>")
                        \(step.elementRole != nil ? "<span class=\"chip role-chip\">\(escapeHTML(step.elementRole!))</span>" : "")
                    </div>
                </div>

                <div class="step-details">
                    <div class="step-info-bar">
                        \(step.windowTitle.isEmpty ? "" : "<div class=\"info-cell\"><span class=\"cell-label\">Window:</span> <strong>\(escapeHTML(step.windowTitle))</strong></div>")
                        \(step.elementTitle != nil ? "<div class=\"info-cell\"><span class=\"cell-label\">Target:</span> <code>\(escapeHTML(step.elementTitle!))</code> <button class=\"copy-micro-btn\" onclick=\"copyText('\(escapeJS(step.elementTitle!))', this)\">Copy</button></div>" : "")
                        \(step.coordinates != nil ? "<div class=\"info-cell\"><span class=\"cell-label\">Coords:</span> <code>(\(Int(step.coordinates!.x)), \(Int(step.coordinates!.y)))</code></div>" : "")
                    </div>

                    \(step.userNotes != nil && !step.userNotes!.isEmpty ? """
                    <div class=\"step-callout note-callout\">
                        <span class=\"callout-icon\">💡</span>
                        <div class=\"callout-text\">\(escapeHTML(step.userNotes!))</div>
                    </div>
                    """ : "")

                    \(step.textBlob != nil && !step.textBlob!.isEmpty ? """
                    <div class=\"code-blob-container\">
                        <div class=\"code-blob-header\">
                            <div class=\"code-blob-meta\">
                                <span class=\"code-icon\">\(step.isCode ? "💻" : "⌨️")</span>
                                <span class=\"code-label\">\(step.isCode ? "Captured Code / Command" : "Typed Text Block")</span>
                                \(step.codeLanguage != nil ? "<span class=\"code-lang-pill\">\(escapeHTML(step.codeLanguage!))</span>" : "")
                            </div>
                            <button class=\"copy-code-btn\" onclick=\"copyText('\(escapeJS(step.textBlob!))', this)\">
                                <svg width=\"13\" height=\"13\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"2\"><rect x=\"9\" y=\"9\" width=\"13\" height=\"13\" rx=\"2\" ry=\"2\"></rect><path d=\"M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1\"></path></svg>
                                <span>Copy to Clipboard</span>
                            </button>
                        </div>
                        <pre class=\"code-blob-body\"><code>\(escapeHTML(step.textBlob!))</code></pre>
                    </div>
                    """ : "")
                </div>

                <!-- Media Section with Toggle Bar -->
                <div class="step-media-container">
                    <div class="media-tabs-header">
                        <span class="media-label">Visual Capture</span>
                        <div class="media-tabs">
                            \(hasScreenshot ? "<button class=\"media-tab-btn \(defaultView == "screenshot" ? "active" : "")\" data-mode=\"screenshot\" onclick=\"switchMediaView(\(step.index), 'screenshot')\">📸 Screenshot</button>" : "")
                            \(hasGif ? "<button class=\"media-tab-btn \(defaultView == "gif" ? "active" : "")\" data-mode=\"gif\" onclick=\"switchMediaView(\(step.index), 'gif')\">🎬 Animated GIF</button>" : "")
                            \(hasWebm ? "<button class=\"media-tab-btn\" data-mode=\"webm\" onclick=\"switchMediaView(\(step.index), 'webm')\">🎥 Micro-Video</button>" : "")
                        </div>
                    </div>

                    <div class="media-viewport">
                        \(hasScreenshot ? """
                        <div class=\"media-view media-view-screenshot \(defaultView == "screenshot" ? "" : "hidden")\">
                            <img src=\"\(prefix)\(step.assets.screenshot!)\" alt=\"\(escapeHTML(step.actionDescription))\" loading=\"lazy\">
                        </div>
                        """ : "")

                        \(hasGif ? """
                        <div class=\"media-view media-view-gif \(defaultView == "gif" ? "" : "hidden")\">
                            <img src=\"\(prefix)\(step.assets.gif!)\" alt=\"Animated \(escapeHTML(step.actionDescription))\" loading=\"lazy\">
                        </div>
                        """ : "")

                        \(hasWebm ? """
                        <div class=\"media-view media-view-webm hidden\">
                            <video src=\"\(prefix)\(step.assets.webm!)\" autoplay loop muted playsinline controls></video>
                        </div>
                        """ : "")
                    </div>
                </div>
            </article>
            """
        }
        return html
    }
    
